package com.suntek.apiconnector.runtime.compile;

import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.HexFormat;

/**
 * {@code planId = sha256(utf8(canonicalNormalizedJson))} lowercase hex.
 *
 * @author Gensokyo
 * @since 2026-09-14
 */
public final class PlanId {

    private PlanId() {
    }

    /**
     * @param canonicalJson canonical normalized JSON
     * @return 64-char lowercase hex
     */
    public static String sha256Hex(String canonicalJson) {
        try {
            MessageDigest digest = MessageDigest.getInstance("SHA-256");
            byte[] hash = digest.digest(canonicalJson.getBytes(StandardCharsets.UTF_8));
            return HexFormat.of().formatHex(hash);
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException("SHA-256 not available", e);
        }
    }
}
